let mongoose = require("mongoose");
let userSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    unique: true,
    required: true,
  },
  password: {
    type: String,
    required: true,
  },
});
let user = mongoose.model("User", userSchema);
module.exports = user;
